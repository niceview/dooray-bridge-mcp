UNKNOWN_TOPIC_MESSAGE = "topic은 reply, new-post, organize, edit 가운데 하나입니다. 비워 두면 목록을 돌려줍니다."


def text_for(topic: str | None, *, write_registered: bool) -> str | None:
    """`None`이면 목록, 모르는 topic이면 `None`. 게이트 끔이면 머리 문단을 붙인다."""
    key = (topic or "").strip().lower()
    if not key:
        text = INDEX
    else:
        found = [body for name, body in TOPICS if name == key]
        if not found:
            return None
        text = found[0]
    if write_registered:
        return text
    return WRITE_OFF_HEAD + "\n\n" + text
